import fs, { readFileSync } from "node:fs";
import { syncBuiltinESMExports } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

// STAND-IN, PoC finding (design § Execution Record, B+ test): R2 FUSE has no hard links, and db.ts publishes every project file with
// `linkSync(tmp, final)` as a write-once idiom (db.ts:624, :675), so every write would fail with EPERM. Fall back to an exclusive copy,
// which keeps the EEXIST semantics the callers rely on. The real fix is a product-code story (S14).
const realLink = fs.linkSync;
(fs as { linkSync: typeof fs.linkSync }).linkSync = (existingPath, newPath) => {
  try {
    realLink(existingPath, newPath);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EPERM") throw error;
    fs.copyFileSync(existingPath, newPath, fs.constants.COPYFILE_EXCL);
  }
};
syncBuiltinESMExports();

// PoC-only: process uptime on a second port, read by the Worker's /__poc/uptime to tell whether the container was ever restarted.
const { createServer } = await import("node:http");
const bootedAt = Date.now();
// PoC-only diagnostics: keep the last ~256 KB of what the process writes to stdout/stderr (Fastify's logger writes through fs.write*),
// so a stuck experiment can be read from outside through the Worker's /__poc/logs.
let logTail = "";
const keep = (chunk: unknown) => {
  logTail = (logTail + (typeof chunk === "string" ? chunk : Buffer.from(chunk as Uint8Array).toString("utf8"))).slice(-262144);
};
const realWriteSync = fs.writeSync;
(fs as { writeSync: typeof fs.writeSync }).writeSync = ((fd: number, data: never, ...rest: never[]) => {
  if (fd === 1 || fd === 2) keep(data);
  return (realWriteSync as (...args: unknown[]) => number)(fd, data, ...rest);
}) as typeof fs.writeSync;
const realWrite = fs.write;
(fs as { write: typeof fs.write }).write = ((fd: number, data: never, ...rest: never[]) => {
  if (fd === 1 || fd === 2) keep(data);
  return (realWrite as (...args: unknown[]) => void)(fd, data, ...rest);
}) as typeof fs.write;
for (const stream of [process.stdout, process.stderr]) {
  const original = stream.write.bind(stream);
  stream.write = ((chunk: unknown, ...rest: unknown[]) => { keep(chunk); return (original as (...args: unknown[]) => boolean)(chunk, ...rest); }) as typeof stream.write;
}
createServer((request, response) => {
  if (request.url?.startsWith("/logs")) return void response.end(logTail);
  response.end(JSON.stringify({ pid: process.pid, uptimeSeconds: Math.round(process.uptime()), bootedAt }));
}).listen(8081, "0.0.0.0");

const backendSrc = process.env.BACKEND_SRC ?? "/app/backend/src";
const load = (file: string) => import(pathToFileURL(join(backendSrc, file)).href);

const { setAssemblyTool } = await load("orchestrator.ts");
const { createFfmpegAssemblyTool } = await load("ffmpegAssemblyTool.ts");
setAssemblyTool(createFfmpegAssemblyTool());

if ((process.env.POC_MODE ?? "real") === "stub") {
  const { setDecompositionDependencies } = await load("decompositionDependencies.ts");
  const { createStubImageProvider, setImageProviderRegistry } = await load("imageProvider.ts");
  const { createStubVoiceProvider, setVoiceProviderRegistry } = await load("voiceProvider.ts");
  const { createStubVideoProvider, setVideoProviderRegistry, STUB_VIDEO_PROVIDER_NAME } = await load("videoProvider.ts");

  const STEP = 0.05;
  setDecompositionDependencies({
    alignmentProvider: {
      async align(_audio: Uint8Array, script: string) {
        return { kind: "success", characters: [...script].map((text, i) => ({ text, start: 0.1 + i * STEP, end: 0.1 + (i + 1) * STEP })) };
      },
    },
    instructionGenerator: {
      async generate(texts: readonly string[]) {
        return { kind: "success", pairs: texts.map((_, i) => ({ image: `image ${i + 1}`, video: `video ${i + 1}` })) };
      },
    },
  });

  // 1920x1088 PNG header: the smallest buffer the image stage's dimension check accepts (copied from test/decomposition-phase.test.ts).
  const png = Buffer.alloc(29);
  png.set([137, 80, 78, 71, 13, 10, 26, 10], 0);
  png.writeUInt32BE(13, 8);
  png.write("IHDR", 12, "ascii");
  png.writeUInt32BE(1920, 16);
  png.writeUInt32BE(1088, 20);
  setImageProviderRegistry({
    defaultIdentifier: "stub-image",
    adapters: { "stub-image": createStubImageProvider("success-bytes", { bytes: png }) },
  });

  setVoiceProviderRegistry({ defaultIdentifier: "stub-voice", adapters: { "stub-voice": createStubVoiceProvider("success") } });

  // A real, decodable clip generated by ffmpeg when the image is built, so real assembly has something to retime.
  const clip = readFileSync(process.env.POC_CLIP_PATH ?? "/app/poc/clip.mp4");
  // POC_STUB_VIDEO_DELAY_MS keeps a request "pending" for that long after its first poll, so a session sits in the video
  // stage long enough to restart the process mid-stage (stubbed stages otherwise finish in about a second).
  const videoDelayMs = Number(process.env.POC_STUB_VIDEO_DELAY_MS ?? 0);
  const baseVideo = createStubVideoProvider("success-bytes", { bytes: clip });
  const firstPolled = new Map<string, number>();
  const video = videoDelayMs > 0
    ? {
        submit: baseVideo.submit.bind(baseVideo),
        async poll(requestId: string) {
          const first = firstPolled.get(requestId) ?? Date.now();
          firstPolled.set(requestId, first);
          if (Date.now() - first < videoDelayMs) return { kind: "pending" as const };
          return baseVideo.poll(requestId);
        },
      }
    : baseVideo;
  setVideoProviderRegistry({
    defaultIdentifier: STUB_VIDEO_PROVIDER_NAME,
    adapters: { [STUB_VIDEO_PROVIDER_NAME]: video },
  });
}
